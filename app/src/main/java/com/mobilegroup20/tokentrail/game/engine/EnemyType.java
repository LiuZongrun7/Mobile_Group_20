package com.mobilegroup20.tokentrail.game.engine;

/**
 * 敌人的三种，以及它们的数值。
 *
 * <p><b>数值放在这儿，不放在 {@link Battlefield} 里。</b>和 {@link ShopCatalog}
 * 的价格一样：这是随时要调的平衡参数，不是规则。守卫波次的曲线在 {@link Waves}，
 * 两者一起决定"这一波难在哪"——曲线管几只、什么搭配，这里管每一只多硬。
 *
 * <h2>三种敌人各自干什么</h2>
 *
 * <p>它们不是"同一个东西换个数"，而是三种压力，逼玩家做不同的应对：
 *
 * <ul>
 *   <li>{@link #GRUNT}——<b>基准</b>。一座 1 级塔正好能在一段射界里打死一只。
 *       所以"一条路配一座塔"是能守住的，玩家第一次布防就有正反馈；</li>
 *   <li>{@link #RUNNER}——<b>快</b>。血少但跑得快，在射界里待的时间最短，
 *       一座塔刚刚够打死一只。<b>它惩罚的是"只摆一座塔"</b>：两只一起来，
 *       塔打死一只、另一只就过去了。要么加塔，要么用墙拖住它；</li>
 *   <li>{@link #BRUTE}——<b>肉</b>。慢到近乎爬，要打很久才倒，
 *       而且是拆墙最快的那个（26 dps，5.8 秒拆掉一面墙）。</li>
 * </ul>
 *
 * <p><b>上面那三条"算得出来"的账是照两种塔各自的射界算的</b>（2026-09-27 重算）：
 * 弩车（射界 3.0 格、34 点一发、2.6 秒装填 ≈ 13.1 dps）贴脸直射，敌人穿过它那片
 * 扇形只有一秒出头，所以它靠的是<b>一发一个</b>而不是"打得久"；大炮（十到二十格、
 * 14 点一发、1 秒装填 = 14 dps）则是在一条十格深的走廊里慢慢磨。
 * <b>这两个数没有重新配平过</b>，见 {@link BuildingStats} 里那段
 * "这三个数现在是待配平的"——所以这里只写"打得死打不死"这个方向，
 * 不写具体秒数：写死了过两天就又是一段过期算术。
 *
 * <p><b>三者的血量/速度/dps 一起看，才是"难度"。</b>只加数量的话，二十只杂兵
 * 和四只杂兵对玩家是同一件事（塔的 dps 是恒定的，多出来的只是排队时间），
 * 所以曲线靠<b>换搭配</b>而不是靠堆数量，见 {@link Waves#composition}。
 *
 * <h2>三种敌人也得长得不一样</h2>
 *
 * <p>上面那些数只有玩家<b>看得出来</b>才有意义。三种兵如果画成同一个红方块，
 * 那"重甲打不死、要两座塔一起打"这件事就永远学不会——玩家只会觉得
 * "有时候怪特别硬"，而不是"我看见重甲了，得多调一座塔过来"。
 *
 * <p>所以每种敌人有自己的 {@link #bodyCells}（多大）和 {@code res/values/colors.xml}
 * 里的颜色（哪一种）。这两样都只是"把上面那张表读出来"，不是新的玩法参数：
 * 体格跟着血量走、颜色跟着分工走。改数值的时候顺手看一眼这两样还配不配。
 *
 * <p><b>体格不只是画多大。</b>它同时是判定用的身位——塔"圈碰到就算打得到"
 * 和敌人"贴到挡路建筑多近"都用它（见 {@link #halfBodyCells()}）。
 * 画的和判的是同一个数，才不会出现"看着大了、判定还是原来那个"。
 *
 * <h2>速度</h2>
 *
 * <p>{@link #GRUNT} 的 0.9 格/秒是<b>原来的全局速度</b>（{@code Battlefield} 里
 * 那个常量），换成本类之后它成了"基准速度"，另外两种相对它定。
 * 从进场（x = −1）走到核心约 72 格，杂兵也就是 <b>80 秒</b>——一波的节奏感来自这里。
 *
 * <p><b>注意：速度是"格/秒"，所以战场一旦变长，节奏就跟着变。</b>
 * 2026-09-27 战场从 40 格宽翻倍到 80 格时，上面这个数就从 33 秒变成了 80 秒
 * （核心跟着挪到了第 71 列）。这两件事是同一件事的两面：路长了一倍，
 * 塔在路上的开火时间也长了一倍，所以那一版之后<b>游戏明显变简单了</b>。
 * 这一组数还没有跟着重配平——要收紧手感，从这里（或者 {@code Waves} 的曲线）下手。
 *
 * <p><b>这一组数是待调的</b>，真机玩两局再改。调的时候记住三个数一起动：
 * 光调血量会让"塔打不死"变成常态，光调 dps 会让墙失去意义。
 */
public enum EnemyType {

    /** 杂兵：基准。一座 1 级塔正好打得死一只。 */
    GRUNT("Grunt", 45f, 0.9f, 12f, 1.0f),

    /** 快兵：血少腿快，一座塔只够打死一只，两只一起来就漏一只。 */
    RUNNER("Runner", 28f, 1.6f, 8f, 0.8f),

    /** 重甲：慢、厚、拆墙最快。一处只有一座 1 级塔的话打不死它。 */
    BRUTE("Brute", 160f, 0.55f, 26f, 1.25f);

    /** 界面和日志里显示的名字。 */
    public final String label;

    /**
     * 满血。
     *
     * <p>是个定值，<b>不随波数涨</b>：难度靠 {@link Waves} 换搭配来给，
     * 不靠"第 5 波的杂兵比第 1 波厚三倍"。后者的问题是玩家看不出区别——
     * 同一个样子、同一个名字，忽然要多打两秒，只会觉得"手感变了"。
     */
    public final float maxHp;

    /** 走多快，格/秒。见类注释里"速度"那一段。 */
    public final float speedCellsPerSec;

    /**
     * 咬建筑有多疼，每秒。
     *
     * <p>被打的是它<b>身体挨着的那几座里最近的一座</b>，不分种类
     * （{@code Battlefield.nearestBite}）——塔、核心、城墙一视同仁。
     * 唯一例外是城墙：只有寻路表真的指进墙里（绕不过去）时才会拆它。
     *
     * <p><b>所以"塔放在敌人不走的路上就绝对安全"仍然成立</b>：敌人只会咬
     * 身体够得着的那几座，隔着两格以上的塔它碰不到，也不会绕过去专门拆。
     * 这也是玩家敢把塔摆在后面的原因。要小心的是<b>紧贴通道摆的那一座</b>——
     * 那是在敌人的射程（确切说是牙程）之内。
     */
    public final float dps;

    /**
     * 体格：身体画多大，单位格。<b>同时也是判定用的身位。</b>
     *
     * <p>跟血量走：杂兵占满自己那一格（{@code 1.0}），快兵瘦一圈，
     * 重甲比一格还宽——"这个不好惹"应该是<b>看一眼就知道</b>的，
     * 而不是让玩家去数血条掉得多慢。
     *
     * <p>纵向也用它：身体从它那一行的底边往上长（和建筑一样贴地），
     * 所以重甲会比一条通道高一点，看着就是一坨。
     *
     * <p>别把它当成纯美术参数——{@link #halfBodyCells()} 会进到
     * {@code Battlefield} 的射程判定和挡路判定里。
     */
    public final float bodyCells;

    EnemyType(String label, float maxHp, float speedCellsPerSec, float dps, float bodyCells) {
        this.label = label;
        this.maxHp = maxHp;
        this.speedCellsPerSec = speedCellsPerSec;
        this.dps = dps;
        this.bodyCells = bodyCells;
    }

    /**
     * 半个身位，单位格。
     *
     * <p>两处用它，都是"碰到"的判定：
     *
     * <ul>
     *   <li>塔打不打得到——加在射程上（{@code Battlefield.frontmostInRange}），
     *       于是"圈碰到身子就算打得到"，不是"圈得够到正中心"；</li>
     *   <li>贴到挡路建筑多近——从那一列减掉（{@code Battlefield.moveEnemies}），
     *       所以身体是<b>右边缘</b>碰到建筑，不是中心碰到。</li>
     * </ul>
     *
     * <p>和画面上那个身子用的是同一个数：不会出现"看着贴上了，判定还差一截"。
     */
    public float halfBodyCells() {
        return bodyCells / 2f;
    }

    /** 它咬得动东西吗。三种都咬，留着这个方法是给以后加"不还手的信使"用的。 */
    public boolean attacks() {
        return dps > 0f;
    }

    @Override
    public String toString() {
        return label;
    }
}
