package com.mobilegroup20.tokentrail.game.engine;

/**
 * 一格地面属于哪一区。<b>能不能建东西，由它说了算</b>，不再由列号硬编码。
 *
 * <p>分三区的理由是"画面上一眼要能看出来这儿能不能放东西"：
 * 玩家在一片 40 格宽的地图上找位置，如果只有"能放/不能放"两种颜色，
 * 他分不清"这块地是留给敌人走的"还是"这块地是山"。所以三区各有各的颜色
 * （见 {@code docs/ART.md} §5 和 {@code BattlefieldView.drawGround}）：
 *
 * <pre>
 *   [ 敌人通道 ][        可放置区        ][ 山区 ]
 *      4 格            约 33 格           3 格
 * </pre>
 *
 * <p><b>敌人通道和山区都不能建</b>，但它们是两回事：通道是"敌人会从这儿过来"，
 * 山区是"这儿根本没有平地"。将来做关卡编辑时，山区是可以随便摆的，
 * 通道则决定了敌人的进攻方向。
 *
 * <p>这个枚举不认识像素、也不认识 {@code android.*}，纯规则——所以哪一格是什么地形
 * 能脱离模拟器测（见 {@code BattlefieldTest}）。
 */
public enum Terrain {

    /**
     * 敌人进场和行进的通道，在战场最左边。
     *
     * <p>不能建东西：这一段是留给玩家"看清敌人从哪条路来"的反应时间。
     */
    ENEMY_LANE,

    /** 可放置区：塔、城墙、核心都只能放在这儿。 */
    BUILDABLE,

    /**
     * 山区：不能建、敌人也不会停的石头地。
     *
     * <p>它在战场最右边，作用是让地图右缘有个"自然的尽头"——不然核心贴到
     * 战场边上，看着像地图被裁掉了。同时也是给"以后要在边上加东西"留的余量。
     */
    MOUNTAIN;

    /** 这一格能不能放建筑。只有 {@link #BUILDABLE} 可以。 */
    public boolean buildable() {
        return this == BUILDABLE;
    }
}
